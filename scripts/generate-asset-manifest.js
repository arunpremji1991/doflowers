const fs = require("node:fs");
const path = require("node:path");

const IMAGE_EXTS = ["webp", "jpg", "jpeg", "png"];
const VIDEO_EXTS = ["mp4", "webm"];

const IMAGE_DIR = path.join(process.cwd(), "public", "uploads", "images");
const VIDEO_DIR = path.join(process.cwd(), "public", "uploads", "video");
const OUT_FILE = path.join(process.cwd(), "src", "lib", "asset-manifest.generated.ts");

function scan(dir, exts) {
  const map = {};
  if (!fs.existsSync(dir)) return map;
  for (const file of fs.readdirSync(dir)) {
    const ext = path.extname(file).slice(1).toLowerCase();
    if (!exts.includes(ext)) continue;
    const seed = path.basename(file, path.extname(file));
    if (!map[seed]) map[seed] = ext;
  }
  return map;
}

const images = scan(IMAGE_DIR, IMAGE_EXTS);
const videos = scan(VIDEO_DIR, VIDEO_EXTS);

const contents = `// Auto-generated by scripts/generate-asset-manifest.js — do not edit by hand.
// Regenerated on every \`npm run dev\` / \`npm run build\`.
export const imageManifest: Record<string, string> = ${JSON.stringify(images, null, 2)};
export const videoManifest: Record<string, string> = ${JSON.stringify(videos, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, contents);
console.log(
  `[assets] ${Object.keys(images).length} image(s), ${Object.keys(videos).length} video(s) found in public/uploads.`
);
